const narrationPath = path.join(root, 'narration.json');
const entries = JSON.parse(fs.readFileSync(narrationPath, 'utf8'));
if (entries.length !== 86) throw new Error(`narration.json should contain 86 entries, found ${entries.length}`);
for (const entry of entries) {
  if (!narrations[entry.page]) throw new Error(`Missing narration for page ${entry.page}`);
  entry.narration = narrations[entry.page];
}
fs.writeFileSync(narrationPath, JSON.stringify(entries, null, 2) + '\n', 'utf8');

const manifestPath = path.join(root, 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
for (const item of manifest) {
  if (!narrations[item.page]) throw new Error(`Missing narration for manifest page ${item.page}`);
  item.narration = narrations[item.page];
}
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');

function walk(dir) {
  const files = [];
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) files.push(...walk(full));
    else if (name.startsWith('page-') && name.endsWith('.html')) files.push(full);
  }
  return files;
}

function escapeHtml(value) {
  return String(value).replace(/[&<>\"]/g, ch => ({ '&':'&amp;', '<':'&lt;', '>':'&gt;', '\"':'&quot;' }[ch]));
}

const pages = walk(root);
if (pages.length !== 86) throw new Error(`Expected 86 HTML pages, found ${pages.length}`);
for (const file of pages) {
  const html = fs.readFileSync(file, 'utf8');
  const name = path.basename(file);
  const page = Number(name.slice(5).split('_')[0]);
  const entry = entries.find(item => item.page === page);
  const panelStart = html.indexOf('<aside id="scriptPanel"');
  const paragraphStart = html.indexOf('<p>', panelStart) + 3;
  const paragraphEnd = html.indexOf('</p>', paragraphStart);
  const metaStart = html.indexOf('window.PAGE_META=');
  const metaEnd = html.indexOf(';</script>', metaStart);
  if (panelStart < 0 || paragraphStart < 3 || paragraphEnd < 0 || metaStart < 0 || metaEnd < 0) {
    throw new Error(`Could not locate narration blocks in ${file}`);
  }
  let next = html.slice(0, paragraphStart) + escapeHtml(entry.narration) + html.slice(paragraphEnd);
  const adjustedMetaStart = next.indexOf('window.PAGE_META=');
  const adjustedMetaEnd = next.indexOf(';</script>', adjustedMetaStart);
  const meta = `window.PAGE_META=${JSON.stringify({ page:entry.page, title:entry.title, narration:entry.narration })};`;
  next = next.slice(0, adjustedMetaStart) + meta + next.slice(adjustedMetaEnd + 1);
  fs.writeFileSync(file, next, 'utf8');
}

